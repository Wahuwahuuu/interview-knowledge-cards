import { readFile } from 'node:fs/promises';
import { readAgentCredential } from './private-credential.mjs';
import { useSystemProxy } from './system-proxy.mjs';
const [file] = process.argv.slice(2);
if (!file) throw new Error('用法：node scripts/agent-import.mjs <JSON文件>');
const suppliedId = process.env.CF_ACCESS_CLIENT_ID, suppliedSecret = process.env.CF_ACCESS_CLIENT_SECRET;
if (Boolean(suppliedId) !== Boolean(suppliedSecret)) throw new Error('请成对提供机器凭证的 Client ID 和 Secret。');
const saved = (!suppliedId && !suppliedSecret) ? await readAgentCredential() : null;
if (saved && process.env.CARDS_SITE_URL && new URL(process.env.CARDS_SITE_URL).origin !== new URL(saved.site_url).origin) throw new Error('本机服务凭证属于原来的题库，不能发送到其他网址。');
const site = new URL(process.env.CARDS_SITE_URL ?? saved?.site_url ?? '');
if (site.protocol !== 'https:' || site.username || site.password || site.search || site.hash) throw new Error('CARDS_SITE_URL 必须是题库自己的 HTTPS 地址，不包含账号、查询参数或凭证');
useSystemProxy(site);
const id = suppliedId ?? saved?.client_id, secret = suppliedSecret ?? saved?.client_secret;
if (!id || !secret) throw new Error('请在当前进程中提供 CF_ACCESS_CLIENT_ID 和 CF_ACCESS_CLIENT_SECRET，不要放入源码或聊天记录');
const data = await readFile(file, 'utf8');
const parsed = JSON.parse(data);
if (parsed.mode === 'restore') throw new Error('完整备份恢复只能从网页上传并确认');
const response = await fetch(new URL('/api/v1/agent/imports/preview', site), { method: 'POST', redirect: 'error', signal: AbortSignal.timeout(30_000), headers: { 'Content-Type': 'application/json', 'CF-Access-Client-Id': id, 'CF-Access-Client-Secret': secret }, body: data });
if (!response.headers.get('content-type')?.includes('application/json')) throw new Error('没有进入机器接口，请检查 Access 路径与服务凭证策略');
const result = await response.json();
if (!response.ok) throw new Error(result.error?.message ?? '提交失败');
console.log(JSON.stringify({ batch_id: result.id, status: result.status, changes: result.preview.map(v => ({ type: v.kind, operation: v.operation, name: v.name })), next: '请在题库的维护与备份页面查看草稿并确认。' }, null, 2));
